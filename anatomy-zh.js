function anatomyChineseText(value) {
 return value.replace(/\s*[（(](?:ACL|PCL)[）)]/g,'').replace(/\bTFCC\b/g,'三角纤维软骨复合体');
}
function renderAnatomyGraphic(plate, large=false) {
 if(plate.asset==='foot-plantar') return `<svg class="anatomy-graphic${large?' anatomy-graphic-large':''}" viewBox="0 0 960 960" role="img" aria-label="${plate.title}：${plate.location.label}"><rect width="960" height="960" fill="white"/>${plantarAnatomySvg()}${renderPainOverlay(plate,960,960)}${renderFootCallout(plate)}</svg>`;
 const data=anatomyZhLabels[plate.asset];
 const [width,height]=data.size;
 const labels=data.labels.map(([text,boxes,options={}])=>{
  const [x,y,w,h]=boxes[0];
  const fontSize=Math.min(34,Math.max(21,h*.72));
  const available=Math.max(...boxes.map(b=>b[2]));
  const textWidth=text.length*fontSize;
  // Long labels fit their existing whitespace; original leader lines remain in place.
  const fit=textWidth>available?` textLength="${available}" lengthAdjust="spacingAndGlyphs"`:'';
  return `<g class="anatomy-zh-label" aria-label="${text}">${boxes.map(([bx,by,bw,bh])=>`<rect x="${bx}" y="${by}" width="${bw}" height="${bh}" fill="${options.fill||'#ffffff'}"/>`).join('')}<text x="${x+3}" y="${y+fontSize+2}" font-size="${fontSize}" fill="${options.color||'#39473b'}" font-family="Microsoft YaHei, PingFang SC, Noto Sans CJK SC, sans-serif"${fit}>${text}</text></g>`;
 }).join('');
 return `<svg class="anatomy-graphic${large?' anatomy-graphic-large':''}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${plate.title}中文标注图：${anatomyChineseText(plate.focus)}；${plate.location?plate.location.label:''}"><rect width="${width}" height="${height}" fill="#ffffff"/><image href="${plate.credit.file}" width="${width}" height="${height}"/>${labels}${renderPainOverlay(plate,width,height)}${renderFootCallout(plate)}</svg>`;
}
